#!/usr/bin/env node
/**
 * ATTRIBUTIONS.md üreticisi.
 *
 * - Çalışma zamanında paketlenen npm bağımlılıklarını (dev hariç) tarar.
 * - Rust registry bağımlılıklarını (Cargo metadata) tarar.
 * - Lisans/telif metinlerini paketlerin kendi LICENSE dosyalarına bırakır;
 *   burada ad, sürüm, lisans ve kaynak bağlantısı listelenir.
 *
 * Kullanım: node scripts/gen-attributions.mjs
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'ATTRIBUTIONS.md');

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return null;
  }
}

function cleanUrl(value) {
  if (!value) return '';
  const raw = typeof value === 'string' ? value : value.url;
  if (!raw) return '';
  return raw
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/\.git$/, '')
    .replace(/^github:/, 'https://github.com/');
}

function npmPackages() {
  let paths = [];
  try {
    const raw = execSync('npm ls --omit=dev --all --parseable', {
      cwd: root,
      encoding: 'utf8',
      maxBuffer: 64 * 1024 * 1024,
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    paths = raw.split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
  } catch (err) {
    const raw = String(err.stdout || '');
    paths = raw.split(/\r?\n/).map((s) => s.trim()).filter(Boolean);
  }
  const seen = new Map();
  for (const dir of paths) {
    if (resolve(dir) === root) continue;
    const pkg = readJson(join(dir, 'package.json'));
    if (!pkg?.name || !pkg.version) continue;
    const license =
      typeof pkg.license === 'string'
        ? pkg.license
        : Array.isArray(pkg.licenses)
          ? pkg.licenses.map((l) => l.type || l).join(', ')
          : pkg.license?.type || '';
    const key = `${pkg.name}@${pkg.version}`;
    if (seen.has(key)) continue;
    seen.set(key, {
      name: pkg.name,
      version: pkg.version,
      license: license || 'See package',
      url: cleanUrl(pkg.repository) || cleanUrl(pkg.homepage),
    });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function cargoPackages() {
  let meta;
  try {
    meta = JSON.parse(
      execSync('cargo metadata --format-version 1 --manifest-path src-tauri/Cargo.toml', {
        cwd: root,
        encoding: 'utf8',
        maxBuffer: 128 * 1024 * 1024,
        stdio: ['ignore', 'pipe', 'ignore'],
      })
    );
  } catch {
    return [];
  }
  const seen = new Map();
  for (const p of meta.packages || []) {
    if (!p.source || !String(p.source).includes('registry+')) continue;
    const key = `${p.name}@${p.version}`;
    if (seen.has(key)) continue;
    seen.set(key, {
      name: p.name,
      version: p.version,
      license: p.license || (Array.isArray(p.license_file) ? '' : 'See crate'),
      url: cleanUrl(p.repository) || cleanUrl(p.homepage),
    });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const npm = npmPackages();
const cargo = cargoPackages();

const table = (rows) =>
  [
    '| Package | Version | License | Source |',
    '|---|---|---|---|',
    ...rows.map(
      (r) => `| \`${r.name}\` | ${r.version} | ${r.license.replace(/\|/g, '\\|')} | ${r.url || '—'} |`
    ),
  ].join('\n');

