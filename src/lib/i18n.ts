const dict: Record<Lang, Record<TranslationKey, string>> = { en, tr };

let lang: Lang = (() => {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    return v === 'tr' ? 'tr' : 'en';
  } catch {
    return 'en';
  }
})();

const listeners = new Set<() => void>();

export const getLang = (): Lang => lang;

export function setLang(next: Lang) {
  if (next === lang) return;
  lang = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* private mode */ }
  listeners.forEach((l) => l());
}

export function subscribeLang(cb: () => void) {
  listeners.add(cb);
  return () => { listeners.delete(cb); };
}

export function translate(l: Lang, key: TranslationKey, params?: Record<string, string | number>): string {
  const s = dict[l]?.[key] ?? en[key] ?? (key as string);
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
}

/** Non-reactive translate (uses the current language). */
export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  return translate(lang, key, params);
}

/** Reactive translate hook — re-renders the component when the language changes. */
export function useT() {
  const l = useSyncExternalStore(subscribeLang, getLang, getLang);
  return (key: TranslationKey, params?: Record<string, string | number>) => translate(l, key, params);
}
